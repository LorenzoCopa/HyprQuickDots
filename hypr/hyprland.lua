-- Set programs that you use.
-- La TERMINAL por defecto NO es fija: se lee de ~/.config/xdg-terminals.list
-- (formato del estándar xdg-terminal-exec; la elige la sección
-- Aplicaciones → Predeterminadas → Terminal de la configuración de
-- quickshell, que además lanza hyprctl reload al cambiarla). Resuelve el
-- Exec del .desktop elegido (sin códigos de campo %f/%U...); si no hay
-- archivo o no se puede resolver, queda kitty.
local terminal = "kitty"
do
	local home = os.getenv("HOME") or ""
	local f = io.open(home .. "/.config/xdg-terminals.list", "r")
	if f then
		local id = ""
		for line in f:lines() do
			id = line:match("^%s*([%w%-%._]+)%s*$") or ""
			if id ~= "" then
				break
			end -- primera línea que sea un ID (sin comentarios/directivas)
		end
		f:close()
		id = id:gsub("%.desktop$", "")
		if id ~= "" then
			local rel = "/" .. id .. ".desktop"
			local dirs = home
				.. "/.local/share/applications"
				.. ":/usr/local/share/applications:/usr/share/applications"
			for base in dirs:gmatch("[^:]+") do
				local df = io.open(base .. rel, "r")
				if df then
					for dline in df:lines() do
						local exec = dline:match("^Exec=(.*)$")
						if exec then
							exec = exec:gsub("%%[fFuUdDnNiCckvm]", ""):gsub("%s+$", "")
							if exec ~= "" then
								terminal = exec
							end
							break
						end
					end
					df:close()
					break
				end
			end
		end
	end
end
