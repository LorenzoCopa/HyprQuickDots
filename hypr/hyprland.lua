local prev_layout = {}
shortcuts.bind(mainMod .. " + M", function()
	local ws = hl.get_active_workspace()
	if not ws then
		return
	end
	local ws_ref = tostring(ws.id)
	if ws.tiled_layout == "monocle" then
		local target = prev_layout[ws_ref] or "master"
		prev_layout[ws_ref] = "monocle"
		hl.workspace_rule({ workspace = ws_ref, layout = target, persistent = true })
	else
		prev_layout[ws_ref] = ws.tiled_layout
		hl.workspace_rule({ workspace = ws_ref, layout = "monocle", persistent = true })
	end
end, nil, "Alternar monocelda en el escritorio activo", "Ventanas")

