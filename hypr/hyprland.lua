local ZOOM_MIN = 1
local ZOOM_MAX = 3

local function zoom(offset)
	local current = hl.get_config("cursor.zoom_factor")
	current = current + offset
	current = math.max(ZOOM_MIN, math.min(ZOOM_MAX, current))
	hl.config({ cursor = { zoom_factor = current } })
end

shortcuts.bind("CTRL + SHIFT + mouse_down", function()
	zoom(-0.5)
end, { repeating = true }, "Alejar (zoom)", "Zoom")

shortcuts.bind("CTRL + SHIFT + mouse_up", function()
	zoom(0.5)
end, { repeating = true }, "Acercar (zoom)", "Zoom")

