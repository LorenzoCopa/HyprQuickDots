-- Volver / ciclar entre ventanas flotantes (SUPER + GRAVE)
local function ventanas_flotantes()
	local ws = hl.get_active_special_workspace() or hl.get_active_workspace()
	local ws_id = ws and (ws.workspace_id or ws.id)
	local flotantes = {}
	local ok, wins = pcall(hl.get_windows)
	if not ok or not wins then
		return flotantes
	end
	for _, win in ipairs(wins) do
		if win.floating and (not ws_id or (win.workspace and win.workspace.id == ws_id)) then
			table.insert(flotantes, win)
		end
	end
	return flotantes
end

shortcuts.bind(mainMod .. " + GRAVE", function()
	local flotantes = ventanas_flotantes()
	if #flotantes == 0 then
		return
	end
	local actual = hl.get_active_window()
	local objetivo = flotantes[1]
	if actual then
		for i, win in ipairs(flotantes) do
			if win.address == actual.address then
				objetivo = flotantes[(i % #flotantes) + 1]
				break
			end
		end
	end
	hl.dispatch(hl.dsp.focus({ window = objetivo }))
	hl.dispatch(hl.dsp.window.alter_zorder({ mode = "top" }))
end, nil, "Alternar entre ventanas flotantes", "Ventanas")
